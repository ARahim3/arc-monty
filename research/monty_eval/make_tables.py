def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p)) if os.path.exists(p) else None


def bucket(e):
    return "1.0" if e >= 0.99 else ("[0.5,1)" if e >= 0.5 else ("(0,0.5)" if e > 0 else "0"))


def distinct_items():
    """Each task once: AGI-1 train + AGI-1 eval + AGI-2 new233 + AGI-2 eval minus its 6 ids already in AGI-1
    (identical demos). The other 767 AGI-2 training tasks are AGI-1 tasks (same pairs) and are not repeated."""
    seen, items = set(), []
    for split in ("agi1-train", "agi1-eval", "new233", "agi2-eval"):
        rows, tasks = cache_for(split), tasks_for(split)
        for k in sorted(tasks):
            if k in seen:
                continue
            seen.add(k)
            items.append((split, k, rows[k], tasks[k]))
    return items


def calibration_distinct():
    from vote_ablation import pool as vpool
    out = {m: collections.defaultdict(lambda: [0, 0.0]) for m in ["full"] + MODULES + [f"{m} (raw)" for m in MODULES]}
    wrong_top = []
    for split, k, row, task in distinct_items():
        for m in MODULES:  # raw per-hypothesis evidence: no within-module accumulation
            best = vpool(build_cands(row, {m}), cross_only=True)
            if best:
                b = out[f"{m} (raw)"][bucket(best[0]["evidence"])]
                b[0] += 1
                b[1] += score_task(task, [[g] for g in best[0]["preds"]])
        fb = pool(build_cands(row))
        if fb and fb[0]["evidence"] >= 0.99 and score_task(task, [[g] for g in fb[0]["preds"]]) < 1:
            wrong_top.append(dict(split=split, task=k, voters=sorted(fb[0]["voters"]), ev=round(fb[0]["evidence"], 3)))
        for m in ["full"] + MODULES:
            best = pool(build_cands(row, None if m == "full" else {m}))
            if not best:
                continue
            top = best[0]
            ok = score_task(task, [[g] for g in top["preds"]])
            b = out[m][bucket(top["evidence"])]
            b[0] += 1
            b[1] += ok
    cal = {m: {b: [v[b][0], round(v[b][1], 2)] for b in BUCKETS} for m, v in out.items()}
    cal["wrong_top_at_1.0"] = wrong_top
    return cal, len(distinct_items())


def pct(a, n):
    return f"{100 * a / n:.1f}%" if n else "-"


def fmt_conf(c, n):
    return f"{c:.0f}/{n}" if n else "0/0"


