"""Static test sets: JSON only, read as data. Keys as research/monty_heldout: relative path without .json, then #test index."""
import glob, json, os
import numpy as np
ROOT = "/Users/abdurrahim/Codes/arc_monty"
X = os.path.join(ROOT, "external")
FRESH = os.path.join(X, "tbt_fresh", "repo", "dataset")
# name: (directory, cluster of a task key, kind)
_task = lambda k: k.split("#")[0]
_type = lambda k: k.split("/")[0]
SETS = {
    "arc-community": (os.path.join(FRESH, "arc-community", "data"), _task, "fresh, hand-made"),
    "nosound": (os.path.join(FRESH, "nosound", "data"), _task, "fresh, hand-made"),
    "dbigham": (os.path.join(FRESH, "dbigham", "data"), _task, "fresh, hand-made, some derived from ARC-AGI-1 tasks"),
    "sequence": (os.path.join(FRESH, "Sequence_ARC", "data"), _task, "fresh, hand-made, 1-D versions of ARC-AGI-1 tasks"),
    "tama": (os.path.join(FRESH, "arc-dataset-tama", "data"), _type, "fresh, generated by a hand-written program, 50 types"),
    "pqa": (os.path.join(FRESH, "PQA", "data"), _type, "fresh, secondary, generated, 7 types"),
    "concept": (os.path.join(X, "judge", "conceptarc", "repo", "corpus"), _task, "spent: ConceptARC"),
    "mini": (os.path.join(X, "heldout", "mini-arc", "data", "MiniARC"), _task, "spent: Mini-ARC"),
    "oned": (os.path.join(X, "heldout", "1d-arc", "dataset"), _type, "spent: 1D-ARC"),
}
EXCLUDE = {"dbigham": ("4938f0c2-easy",)}  # shares an exact pair with development tasks (results/fresh_check.json)


def _g(x):
    return np.array(x, dtype=np.int8)


def load_tasks(name_or_dir):
    """dict key -> task (train [(x, y)], test [x], test_out [y]), for tasks whose test pairs all have outputs."""
    name = name_or_dir if name_or_dir in SETS else None
    path = SETS[name][0] if name else name_or_dir
    out = {}
    for f in sorted(glob.glob(os.path.join(path, "**", "*.json"), recursive=True)):
        try:
            raw = json.load(open(f))
            t = dict(train=[(_g(p["input"]), _g(p["output"])) for p in raw["train"]], test=[_g(p["input"]) for p in raw["test"]],
                     test_out=[_g(p["output"]) for p in raw["test"] if "output" in p])
        except Exception:
            continue
        k = os.path.relpath(f, path)[:-5]
        if t["test_out"] and len(t["test_out"]) == len(t["test"]) and k not in EXCLUDE.get(name, ()):
            out[k] = t
    return out


def items_of(name_or_dir):
    """As monty_heldout.hl_common.items_from_dir: (key#i, demos + that test pair)."""
    return [(f"{k}#{i}", list(t["train"]) + [(x, y)]) for k, t in load_tasks(name_or_dir).items() for i, (x, y) in enumerate(zip(t["test"], t["test_out"]))]
